"""SkillPath Phase 3: one-command evaluation run that stores an exportable replication package.

    python run_evaluation.py profiles.csv
    python run_evaluation.py profiles.csv --skill-map data/skill_map.csv --label final

Runs the researcher's unmodified scripts, in order, on COPIES of the inputs:
    1. prepare_profiles.py   (checks the specification sheet, fills empty acceptable sets)
    2. run_synthetic_tests.py --engine skillpath --app-version <git commit>
    3. analyse_outputs.py
and stores everything in runs/<RUN-ID>/ plus runs/<RUN-ID>.zip:

    inputs/            profiles.csv, skill_map.csv and the skill data used (exact copies)
    profiles_ready.csv acceptable sets as fixed before testing
    test_output_log.csv raw system outputs (one row per recorded response)
    results/           results.xlsx, fig_criteria.png, fig_match.png, analysis_log.txt
    PART3_RESULTS.md   tables ready to paste into Part 3, Section 5
    run_outputs_summary.csv  descriptive summary of what SkillPath recommended
    code/              snapshot of the scripts and engine that produced the run
    manifest.json      date, git commit, versions, constants, commands, exit codes, SHA-256 of every file
    README_RUN.txt     what the package is and how to reproduce it

No research data is created here: profiles and acceptable sets come from the researcher.
"""

from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import json
import os
import platform
import shutil
import subprocess
import sys
import zipfile

import pandas as pd

ROOT = os.path.dirname(os.path.abspath(__file__))
PY = sys.executable


def git(*args: str) -> str:
    try:
        return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()
    except Exception:
        return ""


def sha256(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 16), b""):
            h.update(chunk)
    return h.hexdigest()


def run(cmd: list[str], cwd: str, log: list) -> int:
    print("$", " ".join(os.path.relpath(c, ROOT) if os.path.isabs(c) else c for c in cmd))
    p = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    print(p.stdout.rstrip())
    if p.stderr.strip():
        print(p.stderr.rstrip())
    log.append({"command": [os.path.basename(c) if os.path.isabs(c) else c for c in cmd],
                "exit_code": p.returncode, "stdout": p.stdout, "stderr": p.stderr})
    return p.returncode


def md_table(df: pd.DataFrame) -> str:
    df = df.fillna("")
    cols = list(df.columns)
    out = ["| " + " | ".join(str(c) for c in cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        cells = []
        for c in cols:
            v = r[c]
            cells.append(f"{v:.2f}" if isinstance(v, float) else str(v))
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)


def outputs_summary(log: pd.DataFrame, desc: dict) -> pd.DataFrame:
    base = log[(log.scenario == "baseline") & (log.logic_version == "B")].fillna("")
    rows = []
    for _, r in base.iterrows():
        skill = str(r.recommended_skill)
        d = desc.get(skill.lower(), {})
        rows.append({"profile_id": r.profile_id, "recommended_skill": d.get("label", skill),
                     "category": d.get("category", ""), "wef_skill": d.get("wef_skill", ""),
                     "wef_global_rank": d.get("wef_global_rank", ""),
                     "alternatives": r.alternatives, "fallback": "Y" if skill == "" else "N",
                     "module_difficulties": r.module_difficulties})
    return pd.DataFrame(rows)


def write_part3(run_dir: str, run_id: str, commit: str, summary: pd.DataFrame):
    xl = pd.read_excel(os.path.join(run_dir, "results", "results.xlsx"), sheet_name=None)
    lines = [f"# SkillPath Phase 3 results (run {run_id}, build {commit})", "",
             "Results describe SkillPath outputs for researcher-built synthetic profiles. No real persons involved.",
             "Generated by `run_evaluation.py` from `results/results.xlsx`; figures: `results/fig_criteria.png`, "
             "`results/fig_match.png`.", ""]
    crit = xl["DSR criteria"].copy()
    crit["Result"] = crit["Result"].map(lambda v: f"{v * 100:.1f}%" if pd.notna(v) else "n/a")
    crit["Threshold"] = crit["Threshold"].map(lambda v: f"{v * 100:.0f}%")
    lines += ["## Table 1: DSR evaluation criteria", "",
              md_table(crit[["Criterion", "Metric", "Numerator", "Denominator", "Result", "Threshold", "Met?"]]), ""]
    if "AB paired summary" in xl and len(xl["AB paired summary"]):
        lines += ["## Table 2: Income-visible (A) vs income-neutral (B), paired", "",
                  md_table(xl["AB paired summary"]), ""]
    for sheet, title in [("U2 by competency", "Table 3: Expected-recommendation match by competency level"),
                         ("U2 by discipline", "Table 4: Expected-recommendation match by discipline"),
                         ("U2 by goal", "Table 5: Expected-recommendation match by employment goal")]:
        if sheet in xl and len(xl[sheet]):
            lines += [f"## {title}", "", md_table(xl[sheet]), ""]
    if len(summary):
        rec = summary[summary.fallback == "N"]
        by_cat = rec.groupby("category").size().rename("recommendations").reset_index().sort_values(
            ["recommendations", "category"], ascending=[False, True])
        lines += ["## Table 6: What SkillPath recommended (version B, baseline)", "",
                  f"Profiles with a recommendation: {len(rec)} of {len(summary)}; fallback responses: "
                  f"{int((summary.fallback == 'Y').sum())}.", "", md_table(by_cat), ""]
    with open(os.path.join(run_dir, "PART3_RESULTS.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("profiles", help="researcher's profile specification sheet (CSV)")
    ap.add_argument("--skill-map", default=os.path.join(ROOT, "data", "skill_map.csv"))
    ap.add_argument("--label", default="", help="short label added to the run folder name, e.g. final")
    ap.add_argument("--out-dir", default=os.path.join(ROOT, "runs"))
    ap.add_argument("--allow-dirty", action="store_true",
                    help="run even if the repository has uncommitted changes (marked '-dirty')")
    ap.add_argument("--continue-on-check-problems", action="store_true",
                    help="continue when prepare_profiles.py reports problems (exit code 1)")
    a = ap.parse_args()

    commit = git("rev-parse", "--short", "HEAD") or "nogit"
    dirty = bool(git("status", "--porcelain", "--untracked-files=no"))
    if dirty and not a.allow_dirty:
        sys.exit("Uncommitted changes: commit first so the run is tied to an exact build "
                 "(or use --allow-dirty for a trial run).")
    app_version = commit + ("-dirty" if dirty else "")
    started = dt.datetime.now()
    run_id = "EVAL" + started.strftime("%Y%m%d-%H%M%S") + (f"-{a.label}" if a.label else "")
    run_dir = os.path.join(os.path.abspath(a.out_dir), run_id)
    os.makedirs(os.path.join(run_dir, "inputs"))

    # exact copies of the inputs
    shutil.copy2(a.profiles, os.path.join(run_dir, "inputs", "profiles.csv"))
    shutil.copy2(a.skill_map, os.path.join(run_dir, "inputs", "skill_map.csv"))
    default_map = os.path.abspath(a.skill_map) == os.path.abspath(os.path.join(ROOT, "data", "skill_map.csv"))
    for extra in ([] if not default_map else ["skill_taxonomy.csv", "skill_descriptions.json", "skill_occupation_evidence.csv",
                  "wef_skills_2025.csv", "esco_occupation_skills.json", "skill_map_build.json"]):
        src = os.path.join(ROOT, "data", extra)
        if os.path.exists(src):
            shutil.copy2(src, os.path.join(run_dir, "inputs", extra))
    # code snapshot
    code = os.path.join(run_dir, "code")
    os.makedirs(code)
    for f in ["prepare_profiles.py", "run_synthetic_tests.py", "analyse_outputs.py", "skillpath_adapter.py",
              "requirements.txt"]:
        shutil.copy2(os.path.join(ROOT, f), os.path.join(code, f))
    shutil.copytree(os.path.join(ROOT, "skillpath"), os.path.join(code, "skillpath"),
                    ignore=shutil.ignore_patterns("__pycache__"))

    profiles = os.path.join(run_dir, "inputs", "profiles.csv")
    skill_map = os.path.join(run_dir, "inputs", "skill_map.csv")
    steps = []
    rc = run([PY, os.path.join(ROOT, "prepare_profiles.py"), profiles, skill_map, "--fill-acceptable"], run_dir, steps)
    if rc != 0 and not a.continue_on_check_problems:
        print(f"\nprepare_profiles.py reported problems; fix the sheet and run again. Partial run kept in {run_dir}")
        write_manifest(run_dir, run_id, started, commit, app_version, dirty, a, steps, complete=False)
        sys.exit(1)
    rc = run([PY, os.path.join(ROOT, "run_synthetic_tests.py"), "profiles_ready.csv", skill_map,
              "--app-version", app_version, "--engine", "skillpath", "--out", "test_output_log.csv"], run_dir, steps)
    if rc != 0:
        write_manifest(run_dir, run_id, started, commit, app_version, dirty, a, steps, complete=False)
        sys.exit("run_synthetic_tests.py failed")
    rc = run([PY, os.path.join(ROOT, "analyse_outputs.py"), "profiles_ready.csv", "test_output_log.csv"],
             run_dir, steps)
    if rc != 0:
        write_manifest(run_dir, run_id, started, commit, app_version, dirty, a, steps, complete=False)
        sys.exit("analyse_outputs.py failed")

    desc_path = os.path.join(run_dir, "inputs", "skill_descriptions.json")
    desc = json.load(open(desc_path, encoding="utf-8")) if os.path.exists(desc_path) else {}
    summary = outputs_summary(pd.read_csv(os.path.join(run_dir, "test_output_log.csv"), dtype=str), desc)
    summary.to_csv(os.path.join(run_dir, "run_outputs_summary.csv"), index=False)
    write_part3(run_dir, run_id, app_version, summary)
    with open(os.path.join(run_dir, "README_RUN.txt"), "w", encoding="utf-8") as f:
        f.write(f"""SKILLPATH EVALUATION RUN {run_id}

Engine: SkillPath (--engine skillpath), build {app_version}, run on {started:%Y-%m-%d %H:%M}.
Results describe SkillPath outputs for researcher-built synthetic profiles. No real persons involved.

Contents
- inputs/: exact copies of the profile specification sheet and skill data used.
- profiles_ready.csv: specification sheet after prepare_profiles.py (acceptable sets fixed before testing).
- test_output_log.csv: raw outputs from run_synthetic_tests.py.
- results/: output of analyse_outputs.py (results.xlsx, figures, analysis_log.txt).
- PART3_RESULTS.md: Section 5 tables generated from results/results.xlsx.
- run_outputs_summary.csv: per-profile recommendation, category and demand cluster.
- code/: the scripts and engine used. manifest.json: versions, commands, exit codes, SHA-256 checksums.

Reproduce (from this folder, with the packages in code/requirements.txt):
  python code/prepare_profiles.py inputs/profiles.csv inputs/skill_map.csv --fill-acceptable
  python code/run_synthetic_tests.py profiles_ready.csv inputs/skill_map.csv --app-version {app_version} --engine skillpath
  python code/analyse_outputs.py profiles_ready.csv test_output_log.csv
Outputs should match test_output_log.csv except the run_id and timestamp columns.
""")
    write_manifest(run_dir, run_id, started, commit, app_version, dirty, a, steps, complete=True)
    zip_path = run_dir + ".zip"
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as z:
        for base, _, files in os.walk(run_dir):
            for fn in sorted(files):
                p = os.path.join(base, fn)
                z.write(p, os.path.join(run_id, os.path.relpath(p, run_dir)))
    print(f"\nDone. Run folder: {run_dir}\nExport package: {zip_path}")


def write_manifest(run_dir, run_id, started, commit, app_version, dirty, a, steps, complete):
    from skillpath import config as C
    files = {}
    for base, _, fs in os.walk(run_dir):
        for fn in sorted(fs):
            p = os.path.join(base, fn)
            if fn != "manifest.json":
                files[os.path.relpath(p, run_dir).replace(os.sep, "/")] = sha256(p)
    versions = {}
    for mod in ["pandas", "numpy", "matplotlib", "openpyxl"]:
        try:
            versions[mod] = __import__(mod).__version__
        except Exception:
            pass
    manifest = {
        "run_id": run_id, "complete": complete, "started": started.isoformat(timespec="seconds"),
        "finished": dt.datetime.now().isoformat(timespec="seconds"),
        "git_commit": commit, "git_commit_full": git("rev-parse", "HEAD"), "app_version": app_version,
        "uncommitted_changes": dirty, "label": a.label,
        "python": platform.python_version(), "platform": platform.platform(), "packages": versions,
        "engine_constants": {k: getattr(C, k) for k in ["K", "MODULES", "MODULES_PER_MILESTONE",
                                                         "FAILS_BEFORE_REVISION", "INACTIVE_DAYS_NUDGE",
                                                         "START_LEVELS", "MIN_DIFFICULTY", "MAX_DIFFICULTY"]},
        "steps": [{k: s[k] for k in ("command", "exit_code", "stdout")} for s in steps],
        "sha256": files,
    }
    with open(os.path.join(run_dir, "manifest.json"), "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=1)


if __name__ == "__main__":
    main()
